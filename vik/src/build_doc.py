FONT = "Times New Roman"


def para(text, bold=False, align=WD_ALIGN_PARAGRAPH.JUSTIFY, indent=True, space_before=0):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.alignment = align
    pf.line_spacing = 1.1
    pf.space_after = Pt(6)
    pf.space_before = Pt(space_before)
    if indent:
        pf.first_line_indent = Cm(0.5)
    parts = text if isinstance(text, list) else [(text, bold)]
    for t, b in parts:
        r = p.add_run(t)
        r.font.name = FONT
        r._r.get_or_add_rPr().get_or_add_rFonts().set(
            '{http://schemas.openxmlformats.org/wordprocessingml/2006/main}eastAsia', FONT)
        r.font.size = Pt(13)
        r.bold = b
    return p


def head(text):
    return para(text, bold=True, align=WD_ALIGN_PARAGRAPH.LEFT, indent=False, space_before=6)


